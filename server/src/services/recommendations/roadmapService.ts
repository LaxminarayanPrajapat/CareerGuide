import type { Types } from 'mongoose';
import { COMPATIBILITY_SCORING_VERSION } from '../../config/constants.js';
import { RoadmapModel } from '../../models/Roadmap.js';
import { logger } from '../../utils/logger.js';
import type { CareerMatch } from '../careers/compatibilityService.js';

/**
 * Builds an actionable development roadmap from the gap between the candidate's
 * measured profile and a career's requirements.
 *
 * The structure (stages, ordering, completion criteria) is deterministic. Only
 * the optional `resourceLinks` come from curated, hard-coded, well-known public
 * documentation sites - never from model output.
 *
 * Progress is never set to "completed" here. Items start as `not_started` and
 * only change when the candidate acts or the system verifies an event.
 */
export async function buildRoadmap(options: {
  candidateId: Types.ObjectId | string;
  careerId: Types.ObjectId | string;
  reportId: Types.ObjectId | string;
  reportNumber: string;
  createdBy: Types.ObjectId | string;
  match: CareerMatch;
  careerDoc: {
    title: string;
    description: string;
    learningStages?: Array<{ stage: string; focus: string[] }>;
    suggestedProjects?: string[];
    prerequisites?: string[];
    requiredSkills?: Array<{ skillCode?: string; skillName?: string; developmentFocus?: string }>;
  };
}): Promise<Types.ObjectId> {
  const { candidateId, careerId, reportId, reportNumber, createdBy, match, careerDoc } = options;

  const existing = await RoadmapModel.findOne({ candidate: candidateId, career: careerId });
  if (existing) {
    // Keep the candidate's progress; refresh only the descriptive content.
    existing.summary = match.deterministicSummary;
    existing.priorityGaps = match.gaps.slice(0, 6).map((g) => ({
      skillCode: g.skillCode,
      skillName: g.skillName,
      gap: g.gap,
      priority: g.priority,
    }));
    existing.currentDemonstratedSkills = match.strengths.map((s) => ({
      skillCode: s.skillCode,
      skillName: s.skillName,
      score: s.measured,
    }));
    existing.report = reportId as never;
    existing.scoringVersion = COMPATIBILITY_SCORING_VERSION;
    await existing.save();
    return existing._id;
  }

  const focusByCode = new Map(
    (careerDoc.requiredSkills ?? []).map((r) => [r.skillCode ?? '', r]),
  );

  const items = buildItems(match, careerDoc, focusByCode);

  const milestones = buildMilestones(items);

  const roadmap = await RoadmapModel.create({
    candidate: candidateId as never,
    career: careerId as never,
    report: reportId as never,
    scoringVersion: COMPATIBILITY_SCORING_VERSION,
    title: `${careerDoc.title} development roadmap`,
    summary: match.deterministicSummary,
    currentDemonstratedSkills: match.strengths.map((s) => ({
      skillCode: s.skillCode,
      skillName: s.skillName,
      score: s.measured,
    })),
    priorityGaps: match.gaps.slice(0, 6).map((g) => ({
      skillCode: g.skillCode,
      skillName: g.skillName,
      gap: g.gap,
      priority: g.priority,
    })),
    items,
    milestones,
    progressPercent: 0,
    sourceReportTitle: `Report ${reportNumber}`,
    createdBy: createdBy as never,
    lastActivityAt: new Date(),
  });

  logger.info('roadmap.created', {
    candidateId: String(candidateId),
    careerId: String(careerId),
    itemCount: items.length,
  });

  return roadmap._id;
}

interface DraftItem {
  order: number;
  title: string;
  description: string;
  skillCode?: string;
  kind: 'learn' | 'practice' | 'project' | 'milestone' | 'assess';
  stage: 'beginner' | 'intermediate' | 'advanced';
  estimatedHours: number;
  completionCriteria: string;
  resourceLinks: Array<{ title: string; url: string }>;
}

