function buildItems(
  match: CareerMatch,
  careerDoc: { learningStages?: Array<{ stage: string; focus: string[] }>; suggestedProjects?: string[] },
  focusByCode: Map<string, { developmentFocus?: string } | undefined>,
): DraftItem[] {
  const items: DraftItem[] = [];
  let order = 1;

  const stages: Array<'beginner' | 'intermediate' | 'advanced'> = ['beginner', 'intermediate', 'advanced'];
  const gapsByStage = stages.map((stage) => ({
    stage,
    gaps: match.gaps.filter((g) => g.priority === 'high' || g.priority === 'medium'),
  }));

  for (const stage of stages) {
    const stageFocus = careerDoc.learningStages?.find((s) => s.stage.toLowerCase() === stage)?.focus ?? [];
    const stageGaps = (gapsByStage.find((s) => s.stage === stage)?.gaps ?? []).slice(
      0,
      stage === 'beginner' ? 4 : 3,
    );

    for (const gap of stageGaps) {
      const focus = focusByCode.get(gap.skillCode)?.developmentFocus;
      items.push({
        order: order++,
        title: `Strengthen ${gap.skillName}`,
        description:
          focus && focus.length > 0
            ? focus
            : `Your measured level is about ${Math.round(gap.gap)} points below the level typically required for this role in ${gap.skillName}.`,
        skillCode: gap.skillCode,
        kind: 'learn',
        stage,
        estimatedHours: stage === 'beginner' ? 12 : 8,
        completionCriteria: `Re-take the ${gap.skillName} assessment in this system and demonstrate an improved level.`,
        resourceLinks: RESOURCE_LIBRARY[gap.skillCode] ?? [],
      });

      items.push({
        order: order++,
        title: `Deliberate practice for ${gap.skillName}`,
        description: `Solve or build five short exercises that each target the specific sub-skill behind ${gap.skillName}. Review your mistakes after each one.`,
        skillCode: gap.skillCode,
        kind: 'practice',
        stage,
        estimatedHours: 6,
        completionCriteria: 'Five reviewed exercises are recorded in your portfolio or study notes.',
        resourceLinks: [],
      });
    }

    for (const focus of stageFocus.slice(0, 2)) {
      items.push({
        order: order++,
        title: focus,
        description: `Stage focus from the ${careerDocTitle(match)} career definition: ${focus}.`,
        kind: 'learn',
        stage,
        estimatedHours: 10,
        completionCriteria: 'You can explain the topic and apply it in a small practical task.',
        resourceLinks: [],
      });
    }

    const projectForStage = (careerDoc.suggestedProjects ?? [])[stages.indexOf(stage)];
    if (projectForStage) {
      items.push({
        order: order++,
        title: `Portfolio project: ${projectForStage}`,
        description: projectForStage,
        kind: 'project',
        stage,
        estimatedHours: 20,
        completionCriteria: 'The project is deployed or documented publicly and you can walk through the decisions made.',
        resourceLinks: [],
      });
    }

    items.push({
      order: order++,
      title: `${stage[0].toUpperCase()}${stage.slice(1)} checkpoint assessment`,
      description:
        'Complete the relevant assessments in this system again so the improvement is measured rather than assumed.',
      kind: 'assess',
      stage,
      estimatedHours: 1,
      completionCriteria: 'A new attempt is completed and your skill profile revision increases.',
      resourceLinks: [],
    });
  }

  return items.slice(0, 24);
}

function careerDocTitle(match: CareerMatch): string {
  return match.title;
}

function buildMilestones(items: DraftItem[]) {
  const stages = ['beginner', 'intermediate', 'advanced'] as const;
  return stages.map((stage) => {
    const stageItems = items.filter((i) => i.stage === stage);
    return {
      stage,
      title: `${stage[0].toUpperCase()}${stage.slice(1)} stage`,
      completionCriteria: `Complete every ${stage} stage item in this roadmap.`,
      itemIds: stageItems.map((i) => String(i.order)),
      completed: false,
    };
  });
}

export function recomputeProgress(roadmap: {
  items: Array<{ order: number; status: string }>;
  milestones: Array<{ itemIds: string[]; completed: boolean }>;
  progressPercent: number;
  lastActivityAt: Date;
}): number {
  const total = roadmap.items.length;
  if (total === 0) return 0;
  const completed = roadmap.items.filter((i) => i.status === 'completed').length;
  const inProgress = roadmap.items.filter((i) => i.status === 'in_progress').length;
  const percent = Math.round(((completed + inProgress * 0.5) / total) * 100);
  roadmap.progressPercent = percent;
  roadmap.lastActivityAt = new Date();

  for (const milestone of roadmap.milestones) {
    const related = roadmap.items.filter((i) => milestone.itemIds.includes(String(i.order)));
    milestone.completed = related.length > 0 && related.every((i) => i.status === 'completed');
  }

  return percent;
}
