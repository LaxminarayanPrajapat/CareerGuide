import {
  ASSESSMENT_CATEGORIES,
  DIFFICULTY_LEVELS,
  PREFERENCE_DIMENSIONS,
  type AssessmentCategory,
  type Difficulty,
} from '../../config/constants.js';

export interface SeedOption {
  optionId: string;
  text: string;
  preferencePoints?: number;
}

export interface SeedQuestion {
  /** Stable identifier used by the seed script so re-runs update instead of duplicating. */
  key: string;
  text: string;
  category: AssessmentCategory;
  topic: string;
  questionType: 'mcq' | 'likert';
  difficulty: Difficulty;
  marks: number;
  skillCodes: string[];
  explanation: string;
  options?: SeedOption[];
  correctOptionId?: string;
  preferenceDimension?: string;
  scaleMin?: number;
  scaleMax?: number;
}

const mcq = (
  key: string,
  category: AssessmentCategory,
  topic: string,
  text: string,
  options: [string, string, string, string],
  correctOptionId: string,
  skillCodes: string[],
  explanation: string,
  difficulty: Difficulty = 'medium',
): SeedQuestion => ({
  key,
  text,
  category,
  topic,
  questionType: 'mcq',
  difficulty,
  marks: 1,
  skillCodes,
  explanation,
  options: [
    { optionId: 'a', text: options[0] },
    { optionId: 'b', text: options[1] },
    { optionId: 'c', text: options[2] },
    { optionId: 'd', text: options[3] },
  ],
  correctOptionId,
});

const likert = (
  key: string,
  dimension: string,
  text: string,
  scaleMin: number,
  scaleMax: number,
  skillCodes: string[],
): SeedQuestion => ({
  key,
  text,
  category: 'personality',
  topic: 'Working preferences',
  questionType: 'likert',
  difficulty: 'medium',
  marks: 1,
  skillCodes,
  explanation:
    'This statement contributes to an indicative working-preference profile. There is no correct or incorrect answer.',
  scaleMin,
  scaleMax,
  preferenceDimension: dimension,
  options: [
    { optionId: '1', text: `Strongly disagree (${scaleMin})`, preferencePoints: -2 },
    { optionId: '2', text: `Disagree (${Math.round((scaleMin + scaleMax) / 4)})`, preferencePoints: -1 },
    { optionId: '3', text: `Neutral (${Math.round((scaleMin + scaleMax) / 2)})`, preferencePoints: 0 },
    { optionId: '4', text: `Agree (${Math.round(((scaleMin + scaleMax) * 3) / 4)})`, preferencePoints: 1 },
    { optionId: '5', text: `Strongly agree (${scaleMax})`, preferencePoints: 2 },
  ],
});

